#!/usr/bin/env python3
"""Generate the registered ideographic variation sequences read by build.rs (#1196).

The detector counts a selector after a base no sequence registers. For ideographs the registry
is the IVD, and without it a carrier spending one selector per bit had nothing to answer to,
since the only rule left was how many different selectors a text used.

Only the base and the selector are kept. A sequence registered in several collections is one
row, and which collection registered it does not change what the detector asks.

The release is pinned by date and digest, so a new IVD is a change someone made on purpose.

Run: ``python scripts/gen_ivd_sequences.py`` (writes the TSV in place).
Reproducible: same release in, same bytes out.
"""

from __future__ import annotations

import hashlib
import sys
import urllib.request
from pathlib import Path

RELEASE = "2026-08-03"
SHA256 = "2b466659c2bfde1c52e60bd9fc883ab14dfa5c583df024b80352420265d2cd87"
URL = f"https://www.unicode.org/ivd/data/{RELEASE}/IVD_Sequences.txt"
OUT = (
    Path(__file__).resolve().parent.parent
    / "src"
    / "tables"
    / "data"
    / "ideographic_variation_sequences.tsv"
)


def parse(text: str) -> set[tuple[int, int]]:
    """Every `BASE SELECTOR; COLLECTION; ID` row, as a base and a selector."""
    rows = set()
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        points = data.split(";", 1)[0].split()
        if len(points) != 2:
            raise ValueError(f"not a base and a selector: {line!r}")
        base, selector = (int(point, 16) for point in points)
        if not 0xE0100 <= selector <= 0xE01EF:
            raise ValueError(f"selector outside U+E0100 to U+E01EF: {line!r}")
        rows.add((base, selector))
    return rows


def rows_from(raw: bytes) -> set[tuple[int, int]]:
    """Parse the release, once its digest is the pinned one."""
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SHA256:
        raise ValueError(f"sha256 {digest} is not the pinned {SHA256}")
    return parse(raw.decode("utf-8"))


def main(argv: list[str]) -> int:
    if argv:
        raw = Path(argv[0]).read_bytes()
    else:
        with urllib.request.urlopen(URL, timeout=60) as response:  # noqa: S310 - pinned URL
            raw = response.read()
    rows = rows_from(raw)
    lines = [f"# Generated by scripts/gen_ivd_sequences.py from IVD {RELEASE}. Do not edit."]
    lines += [f"{base:04X}\t{selector:05X}" for base, selector in sorted(rows)]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} sequences -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

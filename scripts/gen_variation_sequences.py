#!/usr/bin/env python3
"""Generate the registered variation sequences read by build.rs.

`strip_format` keeps a presentation selector after a base Unicode registers for it, and the
detector asks the same question of a selector that recurs (#1134, #1135). The answer is two
published files, so it lives in a table and not in a rule about what kind of character a base
is. A rule let any letter qualify, which made `a` + `U+FE0F` a free channel.

Only `U+FE00` to `U+FE0F` are kept. The Mongolian selectors in `StandardizedVariants.txt` have
their own treatment (`docs/limitations.md`), and the ideographic ones are in `IVD_Sequences.txt`,
which this does not read.

Run: ``python scripts/gen_variation_sequences.py`` (writes the TSV in place).
Reproducible: same version in, same bytes out.
"""

from __future__ import annotations

import sys
import urllib.request
from pathlib import Path

UCD_VERSION = "18.0.0"
BASE = f"https://www.unicode.org/Public/{UCD_VERSION}/ucd"
FILES = ("emoji/emoji-variation-sequences.txt", "StandardizedVariants.txt")
OUT = Path(__file__).resolve().parent.parent / "src" / "tables" / "data" / "variation_sequences.tsv"


def parse(text: str) -> set[tuple[int, int]]:
    """Every `BASE SELECTOR ;` row whose selector is `U+FE00` to `U+FE0F`."""
    rows = set()
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        points = data.split(";", 1)[0].split()
        if len(points) != 2:
            raise ValueError(f"not a base and a selector: {line!r}")
        base, selector = (int(point, 16) for point in points)
        if 0xFE00 <= selector <= 0xFE0F:
            rows.add((base, selector))
    return rows


def main() -> int:
    rows: set[tuple[int, int]] = set()
    for name in FILES:
        url = f"{BASE}/{name}"
        with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310 - pinned URL
            rows |= parse(response.read().decode("utf-8"))
    lines = [
        f"# Generated by scripts/gen_variation_sequences.py from UCD {UCD_VERSION}. Do not edit."
    ]
    lines += [f"{base:04X}\t{selector:04X}" for base, selector in sorted(rows)]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} sequences -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
